const DRAW_DURATION = 0.25;
const FILL_DURATION = 0.1;
const PAUSE = 0;
const RESET_PAUSE = 0.05;

const wait = (seconds) =>
   new Promise((resolve) => setTimeout(resolve, seconds * 100));

const Loader = () => {
   const [scope, animate] = useAnimate();
   const mounted = useRef(false);

   useEffect(() => {
      mounted.current = true;

      let cancelled = false;

      const runAnimation = async () => {
         try {
            while (!cancelled && mounted.current && scope.current) {
               // -----------------------------------------
               // 1. HARD RESET
               // -----------------------------------------
               for (const letter of LETTERS) {
                  if (cancelled || !mounted.current || !scope.current) return;

                  await animate(
                     `[data-letter="${letter.id}"]`,
                     {
                        pathLength: 0,
                        fillOpacity: 0,
                        strokeOpacity: 1,
                        opacity: 1,
                     },
                     {
                        duration: 0,
                     },
                  );
               }

               // Give Framer Motion/browser one frame to
               // commit the reset before starting again.
               await wait(RESET_PAUSE);

               if (cancelled || !mounted.current || !scope.current) return;

               // -----------------------------------------
               // 2. DRAW K -> L -> I -> Q -> U -> E
               // -----------------------------------------
               for (const letter of LETTERS) {
                  if (cancelled || !mounted.current || !scope.current) return;

                  const selector = `[data-letter="${letter.id}"]`;

                  // Draw outline
                  await animate(
                     selector,
                     {
                        pathLength: 1,
                        strokeOpacity: 1,
                        fillOpacity: 0,
                     },
                     {
                        duration: DRAW_DURATION,
                        ease: 'easeInOut',
                     },
                  );

                  if (cancelled || !mounted.current || !scope.current) return;

                  // Convert outline into filled letter
                  await animate(
                     selector,
                     {
                        fillOpacity: 1,
                        strokeOpacity: 0,
                     },
                     {
                        duration: FILL_DURATION,
                        ease: 'easeOut',
                     },
                  );
               }

               if (cancelled || !mounted.current || !scope.current) return;

               // -----------------------------------------
               // 3. PAUSE AFTER COMPLETE WORD
               // -----------------------------------------
               await wait(PAUSE);
            }
         } catch (err) {
            // Silently swallow unmount animation errors when scope.current becomes null
         }
      };

      runAnimation();

      return () => {
         cancelled = true;
         mounted.current = false;
      };
   }, [animate]);

   return (
      <div className="fixed inset-0 z-50 flex min-h-[100dvh] w-screen items-center bg-[#16161b] justify-center overflow-hidden backdrop-blur-sm">
         <div
            className={`absolute left-[-8%] top-[-10%] h-[70%] w-[48%] rounded-full blur-[150px] transition-colors duration-500 bg-[#24242d] opacity-80`}
         />
         {/* 
        Adjusted the container width and SVG viewBox specifically for Klique coordinates. 
        Klique bounding box is roughly X: 275 to 1910 and Y: 119 to 620.
      */}
         <div ref={scope} className="relative w-28 sm:w-30 md:w-32">
            <svg
               version="1.1"
               xmlns="http://www.w3.org/2000/svg"
               viewBox="0 0 2100 800"
               className="h-auto w-full overflow-visible">
               {LETTERS.map((letter) => (
                  <g key={letter.id}>
                     {letter.paths.map((d, i) => (
                        <motion.path
                           key={`${letter.id}-${i}`}
                           data-letter={letter.id}
                           d={d}
                           fill="#daf4aa"
                           stroke="#daf4aa"
                           strokeWidth={6}
                           strokeLinejoin="round"
                           strokeLinecap="round"
                           initial={{
                              pathLength: 0,
                              fillOpacity: 0,
                              strokeOpacity: 1,
                              opacity: 1,
                           }}
                        />
                     ))}
                  </g>
               ))}
            </svg>
         </div>
      </div>
   );
};

export default Loader;
